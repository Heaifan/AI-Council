const { chromium } = require("playwright-core");
const path = require("path");
const repoRoot = process.cwd();
const appUrl = "file:///" + path.join(repoRoot, "app", "index.html").replace(/\\/g, "/");
(async () => {
  const browser = await chromium.launch({ channel: "chrome", headless: true });
  const page = await browser.newPage({ viewport: { width: 1180, height: 900 } });
  const errors = [];
  page.on("pageerror", (e) => errors.push("PAGEERROR: " + e.message));
  page.on("console", (m) => { if (m.type() === "error") errors.push("CONSOLE: " + m.text()); });
  await page.goto(appUrl);
  await page.setInputFiles("#dir-input", repoRoot);
  await page.waitForFunction(() => /可用规则 1/.test(document.getElementById("status").textContent), null, { timeout: 30000 });
  await page.click("#tab-btn-meeting");
  const mtCreate = await page.locator("#mt-create").count();
  const disabled = mtCreate ? await page.locator("#mt-create").isDisabled() : "N/A";
  const devtools = await page.locator("#console-devtools").count();
  const seatCards = await page.locator(".seat-card").count();
  const center = await page.locator("#console-center").count();
  console.log(JSON.stringify({ mtCreate, disabled, devtools, seatCards, center, errors }, null, 2));
  await browser.close();
})();
